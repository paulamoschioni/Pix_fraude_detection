-- ================================================================
-- PIX ANTIFRAUDE - MODELO RELACIONAL PARA ESTUDO DE SQL
-- PostgreSQL 14+ | 19 tabelas | UTF-8
-- Dominio: sistema de monitoramento de fraudes em transacoes PIX,
-- com instituicoes financeiras, clientes, contas, chaves PIX,
-- dispositivos, transacoes, alertas do motor antifraude,
-- contestacoes (MED - Mecanismo Especial de Devolucao) e
-- investigacoes.
-- TODOS OS DADOS SAO FICTICIOS (nomes, CPFs, instituicoes).
--
-- Execute em um banco de dados vazio, conectado como um usuario
-- que tenha permissao CREATE.
-- Reexecucao segura: DROP SCHEMA EXCLUSIVO + CREATE SCHEMA.
-- ATENCAO: a opcao abaixo APAGA o schema pix_antifraude e seus dados.
-- ================================================================

BEGIN;

DROP SCHEMA IF EXISTS pix_antifraude CASCADE;
CREATE SCHEMA pix_antifraude;
SET search_path TO pix_antifraude, public;

-- 1. SISTEMA FINANCEIRO --------------------------------------------
CREATE TABLE estado (
    id_estado         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla             CHAR(2) NOT NULL UNIQUE,
    nome              VARCHAR(60) NOT NULL UNIQUE,
    regiao_geografica VARCHAR(15) NOT NULL,
    CONSTRAINT ck_estado_regiao CHECK (regiao_geografica IN
        ('NORTE', 'NORDESTE', 'CENTRO-OESTE', 'SUDESTE', 'SUL'))
);

CREATE TABLE instituicao (
    id_instituicao    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(100) NOT NULL UNIQUE,
    tipo_instituicao  VARCHAR(25) NOT NULL,
    porte             VARCHAR(10) NOT NULL DEFAULT 'PEQUENO',
    data_autorizacao  DATE NOT NULL,
    id_estado         INTEGER NOT NULL REFERENCES estado(id_estado), -- estado da sede
    CONSTRAINT ck_instituicao_tipo CHECK (tipo_instituicao IN
        ('BANCO', 'FINTECH', 'COOPERATIVA', 'INSTITUICAO_PAGAMENTO')),
    CONSTRAINT ck_instituicao_porte CHECK (porte IN
        ('PEQUENO', 'MEDIO', 'GRANDE', 'SISTEMICO'))
);

CREATE TABLE servico (
    id_servico        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(50) NOT NULL UNIQUE
);

-- N:N - servicos oferecidos por cada instituicao.
CREATE TABLE instituicao_servico (
    id_instituicao    INTEGER NOT NULL REFERENCES instituicao(id_instituicao) ON DELETE CASCADE,
    id_servico        INTEGER NOT NULL REFERENCES servico(id_servico),
    PRIMARY KEY (id_instituicao, id_servico)
);

-- Autorrelacionamento: uma instituicao pode ser incorporada por outra
-- (fusoes e aquisicoes). Cadeias permitem "A -> B -> C".
CREATE TABLE incorporacao (
    id_incorporada     INTEGER NOT NULL REFERENCES instituicao(id_instituicao),
    id_incorporadora   INTEGER NOT NULL REFERENCES instituicao(id_instituicao),
    data_incorporacao  DATE NOT NULL,
    tipo_operacao      VARCHAR(10) NOT NULL,
    valor_operacao     NUMERIC(16,2),          -- pode ser nulo (nao divulgado)
    PRIMARY KEY (id_incorporada, id_incorporadora),
    CONSTRAINT ck_incorporacao_distinta CHECK (id_incorporada <> id_incorporadora),
    CONSTRAINT ck_incorporacao_tipo CHECK (tipo_operacao IN ('FUSAO', 'AQUISICAO')),
    CONSTRAINT ck_incorporacao_valor CHECK (valor_operacao IS NULL OR valor_operacao > 0)
);

-- 2. CLIENTES E CONTAS ---------------------------------------------
CREATE TABLE cliente (
    id_cliente        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(120) NOT NULL,
    cpf               CHAR(11) NOT NULL UNIQUE,
    data_nascimento   DATE NOT NULL,
    cidade            VARCHAR(100),
    data_cadastro     DATE NOT NULL DEFAULT CURRENT_DATE,
    id_estado         INTEGER NOT NULL REFERENCES estado(id_estado),
    CONSTRAINT ck_cliente_cpf CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_cliente_maioridade CHECK (data_nascimento <= data_cadastro - INTERVAL '18 years')
);

CREATE TABLE conta (
    id_conta          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apelido           VARCHAR(60),               -- opcional, definido pelo cliente
    agencia           CHAR(4) NOT NULL,
    numero            VARCHAR(12) NOT NULL,
    tipo_conta        VARCHAR(10) NOT NULL,
    saldo             NUMERIC(14,2) NOT NULL DEFAULT 0,
    score_risco       SMALLINT NOT NULL DEFAULT 0,  -- 0 (seguro) a 100 (altissimo risco)
    status_conta      VARCHAR(10) NOT NULL DEFAULT 'ATIVA',
    id_instituicao    INTEGER NOT NULL REFERENCES instituicao(id_instituicao),
    -- Titular ATUAL. Fica nulo quando o titular e removido do cadastro.
    id_cliente        INTEGER REFERENCES cliente(id_cliente) ON DELETE SET NULL,
    CONSTRAINT ck_conta_tipo CHECK (tipo_conta IN ('CORRENTE', 'POUPANCA', 'PAGAMENTO', 'SALARIO')),
    CONSTRAINT ck_conta_saldo CHECK (saldo >= 0),
    CONSTRAINT ck_conta_score CHECK (score_risco BETWEEN 0 AND 100),
    CONSTRAINT ck_conta_status CHECK (status_conta IN ('ATIVA', 'BLOQUEADA', 'ENCERRADA')),
    UNIQUE (id_instituicao, agencia, numero)
);

-- Historico do evento de abertura; o titular atual fica em conta.
-- Quem abriu a conta pode ser diferente do titular atual
-- (transferencia de titularidade - um sinal classico de conta laranja).
CREATE TABLE abertura_conta (
    id_abertura       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conta          INTEGER NOT NULL UNIQUE REFERENCES conta(id_conta),
    id_cliente        INTEGER NOT NULL REFERENCES cliente(id_cliente),
    data_abertura     TIMESTAMP NOT NULL,
    id_estado         INTEGER NOT NULL REFERENCES estado(id_estado), -- onde foi aberta
    canal             VARCHAR(20) NOT NULL DEFAULT 'APP',
    CONSTRAINT ck_abertura_canal CHECK (canal IN
        ('APP', 'INTERNET_BANKING', 'AGENCIA', 'CORRESPONDENTE', 'OUTRO'))
);

-- 3. CATALOGO DE GOLPES --------------------------------------------
CREATE TABLE tipo_golpe (
    id_tipo_golpe     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(100) NOT NULL UNIQUE,
    severidade        SMALLINT NOT NULL DEFAULT 0,          -- 0 a 100
    taxa_recuperacao  NUMERIC(5,2) NOT NULL DEFAULT 0,      -- % medio recuperado
    categoria         VARCHAR(20) NOT NULL,
    id_servico        INTEGER NOT NULL REFERENCES servico(id_servico), -- servico explorado
    CONSTRAINT ck_golpe_severidade CHECK (severidade BETWEEN 0 AND 100),
    CONSTRAINT ck_golpe_recuperacao CHECK (taxa_recuperacao BETWEEN 0 AND 100),
    CONSTRAINT ck_golpe_categoria CHECK (categoria IN
        ('ENGENHARIA_SOCIAL', 'TECNICO', 'DOCUMENTAL'))
);

-- Golpes aos quais cada instituicao esta exposta (mapa de risco).
CREATE TABLE instituicao_golpe (
    id_instituicao    INTEGER NOT NULL REFERENCES instituicao(id_instituicao) ON DELETE CASCADE,
    id_tipo_golpe     INTEGER NOT NULL REFERENCES tipo_golpe(id_tipo_golpe),
    nivel_exposicao   SMALLINT NOT NULL DEFAULT 1,
    PRIMARY KEY (id_instituicao, id_tipo_golpe),
    CONSTRAINT ck_inst_golpe_nivel CHECK (nivel_exposicao BETWEEN 1 AND 100)
);

-- Golpes em que cada conta ja foi identificada como envolvida.
CREATE TABLE conta_golpe (
    id_conta            INTEGER NOT NULL REFERENCES conta(id_conta) ON DELETE CASCADE,
    id_tipo_golpe       INTEGER NOT NULL REFERENCES tipo_golpe(id_tipo_golpe),
    data_identificacao  DATE NOT NULL,
    PRIMARY KEY (id_conta, id_tipo_golpe)
);

-- 4. DISPOSITIVOS E CHAVES PIX -------------------------------------
CREATE TABLE dispositivo (
    id_dispositivo    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente        INTEGER NOT NULL REFERENCES cliente(id_cliente),
    modelo            VARCHAR(60) NOT NULL,
    sistema           VARCHAR(10) NOT NULL,
    data_cadastro     DATE NOT NULL DEFAULT CURRENT_DATE,
    confiavel         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_dispositivo_sistema CHECK (sistema IN ('ANDROID', 'IOS', 'WEB')),
    UNIQUE (id_dispositivo, id_cliente)   -- alvo da FK composta em investigado
);

-- Linhas historicas: a mesma dupla dispositivo/conta pode reaparecer.
CREATE TABLE dispositivo_conta (
    id_vinculo        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dispositivo    INTEGER NOT NULL REFERENCES dispositivo(id_dispositivo) ON DELETE CASCADE,
    id_conta          INTEGER NOT NULL REFERENCES conta(id_conta),
    data_vinculo      DATE NOT NULL,
    data_desvinculo   DATE,
    CONSTRAINT ck_vinculo_datas CHECK (data_desvinculo IS NULL OR data_desvinculo >= data_vinculo),
    UNIQUE (id_dispositivo, id_conta, data_vinculo)
);

-- Seguranca: uma conta so pode estar autorizada em UM dispositivo
-- ativo por vez (data_desvinculo IS NULL).
CREATE UNIQUE INDEX ux_dispositivo_conta_ativo
    ON dispositivo_conta (id_conta) WHERE data_desvinculo IS NULL;

CREATE TABLE chave_pix (
    id_chave          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conta          INTEGER NOT NULL REFERENCES conta(id_conta) ON DELETE CASCADE,
    tipo_chave        VARCHAR(10) NOT NULL,
    valor_chave       VARCHAR(77) NOT NULL,
    data_registro     DATE NOT NULL,
    data_exclusao     DATE,
    CONSTRAINT ck_chave_tipo CHECK (tipo_chave IN ('CPF', 'EMAIL', 'TELEFONE', 'ALEATORIA')),
    CONSTRAINT ck_chave_datas CHECK (data_exclusao IS NULL OR data_exclusao >= data_registro)
);

-- Uma mesma chave nao pode estar ATIVA em duas contas ao mesmo tempo.
CREATE UNIQUE INDEX ux_chave_pix_ativa
    ON chave_pix (valor_chave) WHERE data_exclusao IS NULL;

-- 5. TRANSACOES E MOTOR ANTIFRAUDE ---------------------------------
CREATE TABLE transacao_pix (
    id_transacao      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conta_origem   INTEGER NOT NULL REFERENCES conta(id_conta),
    id_conta_destino  INTEGER NOT NULL REFERENCES conta(id_conta),
    id_dispositivo    INTEGER REFERENCES dispositivo(id_dispositivo), -- nulo = sem dispositivo registrado
    valor             NUMERIC(14,2) NOT NULL,
    data_hora         TIMESTAMP NOT NULL,
    status            VARCHAR(10) NOT NULL DEFAULT 'AGENDADA',
    descricao         VARCHAR(140),
    CONSTRAINT ck_transacao_contas CHECK (id_conta_origem <> id_conta_destino),
    CONSTRAINT ck_transacao_valor CHECK (valor > 0),
    CONSTRAINT ck_transacao_status CHECK (status IN ('AGENDADA', 'CONCLUIDA', 'CANCELADA'))
);

-- Alertas gerados pelo motor antifraude para uma transacao.
-- falso_positivo NULL = alerta ainda nao analisado por um humano.
CREATE TABLE alerta (
    id_alerta         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transacao      BIGINT NOT NULL REFERENCES transacao_pix(id_transacao) ON DELETE CASCADE,
    id_tipo_golpe     INTEGER NOT NULL REFERENCES tipo_golpe(id_tipo_golpe),
    score             SMALLINT NOT NULL,
    data_hora         TIMESTAMP NOT NULL,
    falso_positivo    BOOLEAN,
    CONSTRAINT ck_alerta_score CHECK (score BETWEEN 0 AND 100)
);

-- 6. INVESTIGACOES E CONTESTACOES ----------------------------------
CREATE TABLE investigacao (
    id_investigacao   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(150) NOT NULL UNIQUE,
    orgao             VARCHAR(20) NOT NULL,
    data_inicio       DATE NOT NULL,
    data_fim          DATE NOT NULL,
    valor_bloqueado   NUMERIC(16,2) NOT NULL DEFAULT 0,
    id_estado         INTEGER NOT NULL REFERENCES estado(id_estado),
    CONSTRAINT ck_investigacao_orgao CHECK (orgao IN
        ('POLICIA_CIVIL', 'POLICIA_FEDERAL', 'BACEN', 'COMPLIANCE')),
    CONSTRAINT ck_investigacao_datas CHECK (data_fim >= data_inicio),
    CONSTRAINT ck_investigacao_valor CHECK (valor_bloqueado >= 0)
);

CREATE TABLE investigado (
    id_investigado    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_investigacao   INTEGER NOT NULL REFERENCES investigacao(id_investigacao),
    id_cliente        INTEGER NOT NULL REFERENCES cliente(id_cliente),
    id_dispositivo    INTEGER NOT NULL,   -- dispositivo apreendido/periciado
    data_inclusao     DATE NOT NULL,
    -- O dispositivo periciado precisa pertencer ao proprio investigado.
    CONSTRAINT fk_investigado_dispositivo FOREIGN KEY (id_dispositivo, id_cliente)
        REFERENCES dispositivo (id_dispositivo, id_cliente),
    UNIQUE (id_investigacao, id_cliente)
);

-- Contestacao de uma transacao pela vitima (MED).
-- A vitima e o titular da conta de ORIGEM da transacao.
-- resultado: DEVOLVIDO (valor total), PARCIAL ou NEGADO.
CREATE TABLE contestacao (
    id_contestacao    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transacao      BIGINT NOT NULL UNIQUE REFERENCES transacao_pix(id_transacao),
    id_tipo_golpe     INTEGER NOT NULL REFERENCES tipo_golpe(id_tipo_golpe), -- golpe alegado
    id_investigacao   INTEGER REFERENCES investigacao(id_investigacao),       -- nulo = fora de investigacao
    data_abertura     TIMESTAMP NOT NULL,
    situacao          VARCHAR(12) NOT NULL DEFAULT 'EM_ANALISE',
    resultado         VARCHAR(10),
    valor_devolvido   NUMERIC(14,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_contestacao_situacao CHECK (situacao IN ('EM_ANALISE', 'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT ck_contestacao_resultado CHECK (resultado IS NULL OR resultado IN ('DEVOLVIDO', 'PARCIAL', 'NEGADO')),
    CONSTRAINT ck_contestacao_valor CHECK (valor_devolvido >= 0)
);

