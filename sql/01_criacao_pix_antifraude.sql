-- REGRAS ADICIONAIS: triggers ------------------------------------
-- (1) Regra do Banco Central: no maximo 5 chaves PIX ATIVAS por conta.
CREATE OR REPLACE FUNCTION validar_limite_chaves()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.data_exclusao IS NULL AND (
        SELECT COUNT(*) FROM chave_pix c
        WHERE c.id_conta = NEW.id_conta
          AND c.data_exclusao IS NULL
          AND c.id_chave <> COALESCE(NEW.id_chave, -1)
    ) >= 5 THEN
        RAISE EXCEPTION 'A conta % ja possui 5 chaves PIX ativas', NEW.id_conta;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_limite_chaves
BEFORE INSERT OR UPDATE OF id_conta, data_exclusao ON chave_pix
FOR EACH ROW EXECUTE FUNCTION validar_limite_chaves();

-- (2) O dispositivo usado numa transacao deve pertencer ao titular
--     atual da conta de origem.
CREATE OR REPLACE FUNCTION validar_dispositivo_transacao()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_titular INTEGER;
    v_dono    INTEGER;
BEGIN
    IF NEW.id_dispositivo IS NOT NULL THEN
        SELECT id_cliente INTO v_titular FROM conta WHERE id_conta = NEW.id_conta_origem;
        SELECT id_cliente INTO v_dono FROM dispositivo WHERE id_dispositivo = NEW.id_dispositivo;
        IF v_titular IS NULL OR v_titular <> v_dono THEN
            RAISE EXCEPTION 'Dispositivo % nao pertence ao titular da conta de origem %',
                NEW.id_dispositivo, NEW.id_conta_origem;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_dispositivo_transacao
BEFORE INSERT OR UPDATE OF id_conta_origem, id_dispositivo ON transacao_pix
FOR EACH ROW EXECUTE FUNCTION validar_dispositivo_transacao();

-- (3) Consistencia da contestacao:
--     - so transacoes CONCLUIDAS podem ser contestadas, e depois de ocorrerem;
--     - CONCLUIDA exige resultado; EM_ANALISE/CANCELADA exigem resultado nulo;
--     - DEVOLVIDO = valor total; PARCIAL = entre 0 e o valor; NEGADO = 0.
CREATE OR REPLACE FUNCTION validar_contestacao()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_status VARCHAR(10);
    v_valor  NUMERIC(14,2);
    v_data   TIMESTAMP;
BEGIN
    SELECT status, valor, data_hora INTO v_status, v_valor, v_data
      FROM transacao_pix WHERE id_transacao = NEW.id_transacao;

    IF v_status <> 'CONCLUIDA' THEN
        RAISE EXCEPTION 'Somente transacoes CONCLUIDAS podem ser contestadas (transacao %)', NEW.id_transacao;
    END IF;
    IF NEW.data_abertura < v_data THEN
        RAISE EXCEPTION 'A contestacao nao pode ser anterior a transacao %', NEW.id_transacao;
    END IF;

    IF NEW.situacao = 'CONCLUIDA' THEN
        IF NEW.resultado IS NULL THEN
            RAISE EXCEPTION 'Contestacao concluida exige resultado';
        ELSIF NEW.resultado = 'DEVOLVIDO' AND NEW.valor_devolvido <> v_valor THEN
            RAISE EXCEPTION 'Resultado DEVOLVIDO exige devolucao do valor total';
        ELSIF NEW.resultado = 'PARCIAL' AND NOT (NEW.valor_devolvido > 0 AND NEW.valor_devolvido < v_valor) THEN
            RAISE EXCEPTION 'Resultado PARCIAL exige devolucao entre 0 e o valor da transacao';
        ELSIF NEW.resultado = 'NEGADO' AND NEW.valor_devolvido <> 0 THEN
            RAISE EXCEPTION 'Resultado NEGADO exige valor devolvido igual a zero';
        END IF;
    ELSIF NEW.resultado IS NOT NULL OR NEW.valor_devolvido <> 0 THEN
        RAISE EXCEPTION 'Contestacao % nao concluida nao pode ter resultado nem devolucao', NEW.situacao;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_contestacao
BEFORE INSERT OR UPDATE ON contestacao
FOR EACH ROW EXECUTE FUNCTION validar_contestacao();

COMMIT;

